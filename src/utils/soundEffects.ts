/**
 * Speech synthesis helper using browser Web Speech API
 */
export function speakIndonesian(text: string, onEnd?: () => void): () => void {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    return () => {};
  }

  window.speechSynthesis.cancel();

  // Strip markdown formatting for cleaner audio speech
  const cleanText = text
    .replace(/[*_#`~[\]]/g, '')
    .replace(/•/g, '')
    .replace(/\n+/g, '. ')
    .replace(/[🍉🌱💧🌦️🧠🔌🚜⚡🛑📊📑🏆]/g, '')
    .trim();

  const utterance = new SpeechSynthesisUtterance(cleanText);
  utterance.lang = 'id-ID';
  utterance.rate = 1.05;
  utterance.pitch = 1.1; // Cheerful friendly pitch for Melo

  // Look for Indonesian voice if available
  const voices = window.speechSynthesis.getVoices();
  const indonesianVoice = voices.find(v => v.lang.startsWith('id') || v.lang.includes('ID'));
  if (indonesianVoice) {
    utterance.voice = indonesianVoice;
  }

  if (onEnd) {
    utterance.onend = onEnd;
    utterance.onerror = onEnd;
  }

  window.speechSynthesis.speak(utterance);

  return () => {
    window.speechSynthesis.cancel();
  };
}

export function stopSpeaking() {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.cancel();
  }
}
